export async function seedJacomoFixture(
  client: JacomoSeedDatabase,
  fixture: JacomoFixture = createJacomoFixture(),
): Promise<JacomoFixture> {
  await seed(client, fixture);
  return fixture;
}

export async function withJacomoFixture<T>(
  callback: (fixture: JacomoFixture, sql: JacomoSeedDatabase) => Promise<T>,
  url = process.env.TEST_DATABASE_URL?.trim() || defaultTestUrl,
): Promise<T> {
  const client = postgres(url, { max: 1 });
  try {
    const fixture = await seedJacomoFixture(client);
    return await callback(fixture, client);
  } finally {
    await client.end({ timeout: 5 });
  }
}

export async function readJacomoCounts(sql: JacomoSeedDatabase, fixture = createJacomoFixture()) {
  const tables = [
    "advertiser",
    "brand",
    "product",
    "product_variant",
    "file_object",
    "design_asset",
    "asset_version",
    "campaign",
    "campaign_product",
    "campaign_asset",
    "campaign_format_selection",
  ] as const;
  const counts: Record<string, number> = {};
  for (const table of tables) {
    const rows = await sql.unsafe<{ count: string }[]>(
      `SELECT count(*)::text AS count FROM ${table} WHERE workspace_id = $1`,
      [fixture.workspace.id],
    );
    counts[table] = Number(rows[0]?.count ?? 0);
  }
  for (const [table, id] of [
    ["workspace", fixture.workspace.id],
    ["user_account", fixture.owner.id],
    ["channel", fixture.catalog.channelId],
    ["format_profile", fixture.catalog.formatProfileId],
    ["layout_template", fixture.catalog.layoutTemplateId],
  ] as const) {
    const rows = await sql.unsafe<{ count: string }[]>(
      `SELECT count(*)::text AS count FROM ${table} WHERE id = $1`,
      [id],
    );
    counts[table] = Number(rows[0]?.count ?? 0);
  }
  return counts;
}

